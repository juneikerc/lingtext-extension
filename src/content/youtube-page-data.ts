// Runs in the page's MAIN world at document_start. It must stay
// self-contained (no imports) so it bundles into a single classic script.
//
// YouTube's caption URLs (`exp=xpe`) return an empty 200 unless the request
// carries the player's proof-of-origin token (`pot`). The content script
// can't mint that token, so we watch the player's own `/api/timedtext`
// requests, keep the English payload, and hand it to the content script.

interface CaptionTrack {
  baseUrl?: string;
  languageCode?: string;
  kind?: string;
  vssId?: string;
}

interface PlayerResponse {
  videoDetails?: { videoId?: string };
  captions?: {
    playerCaptionsTracklistRenderer?: { captionTracks?: CaptionTrack[] };
  };
}

interface CapturedTranscript {
  videoId: string;
  languageCode: string;
  isAutoGenerated: boolean;
  payload: string;
}

const TIMEDTEXT_PATH = "/api/timedtext";
// Params that identify which track is fetched. Everything else on the
// player's request (pot, c, cver, xorb, …) is client/attestation context we
// copy onto our own request for the preferred English track.
const TRACK_PARAMS = new Set(["v", "lang", "kind", "name", "tlang", "fmt"]);

const captures = new Map<string, CapturedTranscript>();
const inFlight = new Set<string>();
const originalFetch = window.fetch.bind(window);

function extractTracksFromResponse(response: unknown): {
  videoId?: string;
  tracks: CaptionTrack[];
} {
  const candidate = response as PlayerResponse | undefined;
  const tracks =
    candidate?.captions?.playerCaptionsTracklistRenderer?.captionTracks;

  return {
    videoId: candidate?.videoDetails?.videoId,
    tracks: Array.isArray(tracks) ? tracks : [],
  };
}

function readPlayerResponse(): { videoId?: string; tracks: CaptionTrack[] } {
  // The live player object stays current across SPA navigations, unlike
  // ytInitialPlayerResponse which keeps the first video loaded in the tab.
  const player = document.getElementById("movie_player") as
    | (HTMLElement & { getPlayerResponse?: () => unknown })
    | null;

  try {
    const fromPlayer = extractTracksFromResponse(player?.getPlayerResponse?.());
    if (fromPlayer.videoId) {
      return fromPlayer;
    }
  } catch {
    // Fall through to the page globals.
  }

  const runtime = window as unknown as {
    ytInitialPlayerResponse?: unknown;
    ytplayer?: { config?: { args?: { player_response?: string } } };
  };

  const fromInitial = extractTracksFromResponse(
    runtime.ytInitialPlayerResponse
  );
  if (fromInitial.tracks.length > 0) {
    return fromInitial;
  }

  const rawPlayerResponse = runtime.ytplayer?.config?.args?.player_response;
  if (typeof rawPlayerResponse === "string" && rawPlayerResponse) {
    try {
      return extractTracksFromResponse(JSON.parse(rawPlayerResponse));
    } catch {
      return { tracks: [] };
    }
  }

  return { tracks: [] };
}

function isAsrTrack(track: CaptionTrack): boolean {
  const vssId = (track.vssId || "").toLowerCase();
  return track.kind === "asr" || vssId.startsWith("a.");
}

function isEnglishTrack(track: CaptionTrack): boolean {
  const languageCode = (track.languageCode || "").toLowerCase();
  const vssId = (track.vssId || "").toLowerCase();
  return languageCode.startsWith("en") || vssId.includes(".en");
}

function pickEnglishTrack(tracks: CaptionTrack[]): CaptionTrack | null {
  const englishTracks = tracks.filter(isEnglishTrack);
  return englishTracks.find((track) => !isAsrTrack(track)) || englishTracks[0] || null;
}

function readTracksForVideo(videoId: string): CaptionTrack[] {
  const data = readPlayerResponse();
  return data.videoId === videoId ? data.tracks : [];
}

function toUrl(input: string): URL | null {
  try {
    return new URL(input, window.location.href);
  } catch {
    return null;
  }
}

function isTimedtextUrl(input: string): boolean {
  return input.includes(TIMEDTEXT_PATH);
}

function requestMatchesTrack(url: URL, track: CaptionTrack): boolean {
  if (url.searchParams.get("tlang")) {
    return false;
  }

  const lang = (url.searchParams.get("lang") || "").toLowerCase();
  const trackLang = (track.languageCode || "").toLowerCase();
  const requestIsAsr = url.searchParams.get("kind") === "asr";

  return lang === trackLang && requestIsAsr === isAsrTrack(track);
}

function buildTrackUrl(track: CaptionTrack, playerRequest: URL): string | null {
  if (!track.baseUrl) {
    return null;
  }

  const url = toUrl(track.baseUrl.replace(/\\u0026/g, "&"));
  if (!url) {
    return null;
  }

  playerRequest.searchParams.forEach((value, key) => {
    if (!TRACK_PARAMS.has(key) && !url.searchParams.has(key)) {
      url.searchParams.set(key, value);
    }
  });
  url.searchParams.set("fmt", "json3");

  return url.toString();
}

function publish(capture: CapturedTranscript) {
  captures.set(capture.videoId, capture);
  window.postMessage(
    { type: "LINGTEXT_YOUTUBE_TIMEDTEXT", payload: capture },
    window.location.origin
  );
}

async function handleTimedtextResponse(rawUrl: string, body: string) {
  const url = toUrl(rawUrl);
  const videoId = url?.searchParams.get("v");
  if (!url || !videoId) {
    return;
  }

  const lang = (url.searchParams.get("lang") || "").toLowerCase();
  const isEnglishRequest = !url.searchParams.get("tlang") && lang.startsWith("en");
  const requestIsAsr = url.searchParams.get("kind") === "asr";
  const hasBody = body.trim().length > 0;

  const preferred = pickEnglishTrack(readTracksForVideo(videoId));
  const existing = captures.get(videoId);

  // The player is already showing the track we want: use its payload as-is.
  if (isEnglishRequest && hasBody && (!preferred || requestMatchesTrack(url, preferred))) {
    if (existing?.payload !== body) {
      publish({ videoId, languageCode: lang, isAutoGenerated: requestIsAsr, payload: body });
    }
    return;
  }

  // The player shows another track (Spanish, auto-translated, or ASR while a
  // manual English track exists). Reuse its token to fetch the English one.
  if (preferred && !existing && !inFlight.has(videoId)) {
    const trackUrl = buildTrackUrl(preferred, url);
    if (trackUrl) {
      inFlight.add(videoId);
      try {
        const response = await originalFetch(trackUrl, { credentials: "include" });
        const text = response.ok ? await response.text() : "";
        if (text.trim()) {
          publish({
            videoId,
            languageCode: (preferred.languageCode || "en").toLowerCase(),
            isAutoGenerated: isAsrTrack(preferred),
            payload: text,
          });
          return;
        }
      } catch {
        // Fall back to the player's payload below.
      } finally {
        inFlight.delete(videoId);
      }
    }
  }

  if (isEnglishRequest && hasBody && !captures.has(videoId)) {
    publish({ videoId, languageCode: lang, isAutoGenerated: requestIsAsr, payload: body });
  }
}

function onTimedtext(rawUrl: string, body: string) {
  handleTimedtextResponse(rawUrl, body).catch(() => {
    // Never let caption capture break the player.
  });
}

function requestUrlOf(input: RequestInfo | URL): string {
  if (typeof input === "string") {
    return input;
  }
  if (input instanceof URL) {
    return input.href;
  }
  return input.url;
}

window.fetch = function patchedFetch(
  this: unknown,
  input: RequestInfo | URL,
  init?: RequestInit
): Promise<Response> {
  const promise = originalFetch(input, init);
  let rawUrl = "";
  try {
    rawUrl = requestUrlOf(input);
  } catch {
    rawUrl = "";
  }

  if (isTimedtextUrl(rawUrl)) {
    promise
      .then((response) => (response.ok ? response.clone().text() : ""))
      .then((body) => onTimedtext(rawUrl, body))
      .catch(() => {});
  }

  return promise;
} as typeof window.fetch;

const xhrUrls = new WeakMap<XMLHttpRequest, string>();
const originalOpen = XMLHttpRequest.prototype.open;
const originalSend = XMLHttpRequest.prototype.send;

XMLHttpRequest.prototype.open = function patchedOpen(
  this: XMLHttpRequest,
  ...args: unknown[]
) {
  const url = args[1];
  xhrUrls.set(this, typeof url === "string" ? url : url instanceof URL ? url.href : "");
  return (originalOpen as (...a: unknown[]) => void).apply(this, args);
} as typeof XMLHttpRequest.prototype.open;

function readXhrBody(xhr: XMLHttpRequest): string {
  switch (xhr.responseType) {
    case "":
    case "text":
      return xhr.responseText;
    case "arraybuffer":
      return xhr.response instanceof ArrayBuffer
        ? new TextDecoder().decode(xhr.response)
        : "";
    case "json":
      return xhr.response ? JSON.stringify(xhr.response) : "";
    default:
      return "";
  }
}

XMLHttpRequest.prototype.send = function patchedSend(
  this: XMLHttpRequest,
  body?: Document | XMLHttpRequestBodyInit | null
) {
  const rawUrl = xhrUrls.get(this) || "";
  if (isTimedtextUrl(rawUrl)) {
    this.addEventListener("load", () => {
      if (this.status < 200 || this.status >= 300) {
        return;
      }
      try {
        onTimedtext(this.responseURL || rawUrl, readXhrBody(this));
      } catch {
        // Ignore unreadable bodies.
      }
    });
  }
  return originalSend.call(this, body);
};

window.addEventListener("message", (event) => {
  if (event.source !== window || event.origin !== window.location.origin) {
    return;
  }

  const { type, requestId, videoId } = event.data || {};

  if (type === "LINGTEXT_GET_YOUTUBE_CAPTION_TRACKS") {
    window.postMessage(
      {
        type: "LINGTEXT_YOUTUBE_CAPTION_TRACKS",
        requestId,
        payload: readPlayerResponse(),
      },
      window.location.origin
    );
    return;
  }

  if (type === "LINGTEXT_GET_YOUTUBE_TIMEDTEXT" && typeof videoId === "string") {
    window.postMessage(
      {
        type: "LINGTEXT_YOUTUBE_TIMEDTEXT_RESPONSE",
        requestId,
        payload: captures.get(videoId) || null,
      },
      window.location.origin
    );
  }
});
